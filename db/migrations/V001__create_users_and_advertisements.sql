CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    first_name text NOT NULL CHECK (first_name ~ '[^[:space:]]'),
    last_name text NOT NULL CHECK (last_name ~ '[^[:space:]]'),
    is_verified boolean NOT NULL DEFAULT false,
    violations_qty integer NOT NULL DEFAULT 0 CHECK (violations_qty >= 0)
);

CREATE TABLE advertisements (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    seller_id integer NOT NULL REFERENCES users (id),
    name varchar(255) NOT NULL CHECK (name ~ '[^[:space:]]'),
    description varchar(5000) NOT NULL CHECK (description ~ '[^[:space:]]'),
    category integer NOT NULL CHECK (category >= 0),
    images_qty integer NOT NULL CHECK (images_qty >= 0)
);

CREATE INDEX advertisements_seller_id_idx ON advertisements (seller_id);
